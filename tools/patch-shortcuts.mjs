// Adds the launcher shortcuts to the generated project: long press the icon,
// get Mark today and Arena. Each is a deep link through the open host that
// tools/patch-deeplink.mjs registers, so the web layer decides the screen.
//
// android/ is regenerated on every build, so this runs after `cap sync`, like
// the other patch scripts. Labels have to be string resources and the icons
// vector drawables, both written here from the app's own icon table so the
// glyphs on the launcher are the ones on screen.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { icon } from '../www/js/icons.js';

const MANIFEST = 'android/app/src/main/AndroidManifest.xml';
const RES = 'android/app/src/main/res';
const PACKAGE = 'com.habitnemesis.app';
const SCHEME = 'com.habitnemesis.app';

const SHORTCUTS = [
  { id: 'mark', route: 'hub', short: 'Mark today', long: 'Mark today on the grid', glyph: 'check' },
  { id: 'arena', route: 'arena', short: 'Arena', long: 'This week in the Arena', glyph: 'versus' },
];

if (!existsSync(MANIFEST)) {
  console.error(`${MANIFEST} not found. Run \`npx cap add android\` first.`);
  process.exit(1);
}

/* ---- the drawables ---- */
// A vector drawable from the inline SVG: paths and circles only, which is all
// the two glyphs use. Accent disc, white stroke, glyph at half size.

const ACCENT = '#e62429';
const ON_ACCENT = '#ffffff';

function pathData(svg) {
  const out = [];
  for (const [, d] of svg.matchAll(/<path d="([^"]+)"/g)) out.push(d);
  for (const [, cx, cy, r] of svg.matchAll(/<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"/g)) {
    out.push(`M${cx},${cy}m-${r},0a${r},${r} 0 1,0 ${r * 2},0a${r},${r} 0 1,0 -${r * 2},0`);
  }
  if (!out.length) throw new Error('no path in the glyph');
  return out;
}

const drawable = (glyph) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/patch-shortcuts.mjs from www/js/icons.js. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp" android:height="48dp"
    android:viewportWidth="24" android:viewportHeight="24">
    <path android:pathData="M12,12m-12,0a12,12 0 1,0 24,0a12,12 0 1,0 -24,0" android:fillColor="${ACCENT}" />
    <group android:scaleX="0.5" android:scaleY="0.5" android:pivotX="12" android:pivotY="12">
${pathData(icon(glyph)).map((d) => `        <path android:pathData="${d}" android:strokeColor="${ON_ACCENT}" android:strokeWidth="2"
            android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />`).join('\n')}
    </group>
</vector>
`;

/* ---- the resources ---- */

const strings = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/patch-shortcuts.mjs. -->
<resources>
${SHORTCUTS.map((s) => `    <string name="shortcut_${s.id}_short">${s.short}</string>
    <string name="shortcut_${s.id}_long">${s.long}</string>`).join('\n')}
</resources>
`;

const shortcuts = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/patch-shortcuts.mjs. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
${SHORTCUTS.map((s, i) => `    <shortcut
        android:shortcutId="${s.id}"
        android:enabled="true"
        android:icon="@drawable/ic_shortcut_${s.id}"
        android:shortcutShortLabel="@string/shortcut_${s.id}_short"
        android:shortcutLongLabel="@string/shortcut_${s.id}_long">
        <intent
            android:action="android.intent.action.VIEW"
            android:data="${SCHEME}://open?route=${s.route}"
            android:targetPackage="${PACKAGE}"
            android:targetClass="${PACKAGE}.MainActivity" />
    </shortcut>`).join('\n')}
</shortcuts>
`;

mkdirSync(`${RES}/xml`, { recursive: true });
mkdirSync(`${RES}/values`, { recursive: true });
mkdirSync(`${RES}/drawable`, { recursive: true });
writeFileSync(`${RES}/xml/shortcuts.xml`, shortcuts);
writeFileSync(`${RES}/values/shortcuts.xml`, strings);
for (const s of SHORTCUTS) writeFileSync(`${RES}/drawable/ic_shortcut_${s.id}.xml`, drawable(s.glyph));

/* ---- the manifest ---- */

let xml = readFileSync(MANIFEST, 'utf8');
const META = '<meta-data android:name="android.app.shortcuts" android:resource="@xml/shortcuts" />';
if (xml.includes(META)) {
  console.log('shortcuts already registered');
  process.exit(0);
}

// Inside the launcher activity, which is the one after the launcher filter.
const LAUNCHER = '<category android:name="android.intent.category.LAUNCHER" />';
const at = xml.indexOf(LAUNCHER);
if (at < 0) {
  console.error('No launcher intent filter in the manifest. Capacitor changed its template.');
  process.exit(1);
}
const close = xml.indexOf('</activity>', at);
if (close < 0) {
  console.error('Malformed manifest: the launcher activity never closes.');
  process.exit(1);
}
xml = `${xml.slice(0, close)}    ${META}\n        ${xml.slice(close)}`;
writeFileSync(MANIFEST, xml);

if (!readFileSync(MANIFEST, 'utf8').includes(META)) {
  console.error('The meta-data did not land. Manifest left as it was.');
  process.exit(1);
}
console.log(`shortcuts registered: ${SHORTCUTS.map((s) => s.short).join(', ')}`);
